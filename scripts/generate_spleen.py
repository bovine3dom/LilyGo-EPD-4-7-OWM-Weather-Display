#!/usr/bin/env python3
"""Generate the firmware's Spleen bitmap fonts from the upstream BDF files."""

import argparse
from pathlib import Path
import re
import urllib.request
import zlib

REVISION = "5116f8eac7f65da2cfa169626ec43b5d041665fe"
FONTS = (
    ("Spleen16", "spleen-8x16.bdf", 1, False),
    ("Spleen24", "spleen-12x24.bdf", 1, False),
    ("Spleen32", "spleen-16x32.bdf", 1, False),
    ("Spleen24Bold", "spleen-12x24.bdf", 1, True),
    ("Spleen48Bold", "spleen-12x24.bdf", 2, True),
    ("Spleen64Bold", "spleen-32x64.bdf", 1, True),
)
CODES = list(range(0x20, 0x7f)) + list(range(0xa0, 0x100))


def read_font(source, scale, bold):
    size, ascent, descent = (int(re.search(rf"^{key} (\d+)", source, re.M).group(1)) * scale
                             for key in ("PIXEL_SIZE", "FONT_ASCENT", "FONT_DESCENT"))
    glyphs = {}
    for block in source.split("STARTCHAR ")[1:]:
        encoding = re.search(r"^ENCODING (-?\d+)", block, re.M)
        box = re.search(r"^BBX (\d+) (\d+) (-?\d+) (-?\d+)", block, re.M)
        advance = re.search(r"^DWIDTH (\d+)", block, re.M)
        bitmap = re.search(r"^BITMAP\n(.*?)\nENDCHAR", block, re.M | re.S)
        if not (encoding and box and advance and bitmap):
            continue
        code = int(encoding.group(1))
        if code not in CODES:
            continue
        width, height, left, bottom = map(int, box.groups())
        rows = []
        for line in bitmap.group(1).splitlines():
            row = bytes.fromhex(line.strip())
            pixels = [15 if row[x // 8] & (0x80 >> (x % 8)) else 0
                      for x in range(width) for _ in range(scale)]
            if bold:
                pixels = [15 if pixels[x] or (x and pixels[x - 1]) else 0
                          for x in range(len(pixels))]
            packed = bytes(pixels[x] | (pixels[x + 1] << 4 if x + 1 < len(pixels) else 0)
                           for x in range(0, len(pixels), 2))
            rows.extend([packed] * scale)
        raw = b"".join(rows)
        assert len(raw) == ((width * scale + 1) // 2) * height * scale
        glyphs[code] = (width * scale, height * scale, int(advance.group(1)) * scale,
                        left * scale, (bottom + height) * scale, zlib.compress(raw))
    return size, ascent, descent, glyphs


def emit_font(name, size, ascent, descent, glyphs):
    data = bytearray()
    records = []
    for code in CODES:
        width, height, advance, left, top, bitmap = glyphs.get(code, glyphs[ord("?")])
        records.append(f"{{{width},{height},{advance},{left},{top},{len(bitmap)},{len(data)}}}")
        data.extend(bitmap)
    lines = [f"static const uint8_t {name}Data[] = {{"]
    lines.extend("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 32]) + ","
                 for i in range(0, len(data), 32))
    lines.append("};")
    lines.append(f"static const GFXglyph {name}Glyphs[] = {{")
    lines.extend("    " + ",".join(records[i:i + 4]) + "," for i in range(0, len(records), 4))
    lines.extend(("};", f"static const UnicodeInterval {name}Intervals[] = {{{{0x20,0x7e,0}},{{0xa0,0xff,95}}}};",
                  f"static const GFXfont {name} = {{(uint8_t*){name}Data,(GFXglyph*){name}Glyphs,"
                  f"(UnicodeInterval*){name}Intervals,2,true,{size},{ascent},-{descent}}};"))
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, help="Directory containing the upstream BDF files")
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parent.parent / "fonts" / "spleen.h")
    args = parser.parse_args()
    sources = {}
    for _, filename, _, _ in FONTS:
        if filename in sources:
            continue
        if args.source_dir:
            sources[filename] = (args.source_dir / filename).read_text()
        else:
            url = f"https://raw.githubusercontent.com/fcambus/spleen/{REVISION}/{filename}"
            with urllib.request.urlopen(url) as response:
                sources[filename] = response.read().decode("utf-8")
    output = ['// Generated by scripts/generate_spleen.py. See fonts/Spleen.LICENSE.',
              '#pragma once', '#include "epd_driver.h"']
    for name, filename, scale, bold in FONTS:
        output.append(emit_font(name, *read_font(sources[filename], scale, bold)))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n\n".join(output) + "\n")


if __name__ == "__main__":
    main()
